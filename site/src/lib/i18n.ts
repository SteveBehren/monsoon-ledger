/** 2025-04-30 becomes "30 April 2025" in both languages. */
export function fmtDate(lang: Lang, iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  return `${d} ${MONTHS[lang].long[m - 1]} ${y}`;
}

